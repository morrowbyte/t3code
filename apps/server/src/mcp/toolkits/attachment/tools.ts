import { McpAttachmentInput } from "./input.ts";
import {
  AttachmentCreateUploadUrlInput,
  AttachmentCreateUploadUrlResult,
  AttachmentDeleteInput,
  MessageId,
  RunId,
  ThreadId,
  OrchestrationV2RunStatus,
  OrchestratorMcpFailure,
  EnvironmentId,
} from "@t3tools/contracts";
import * as Crypto from "effect/Crypto";
import * as FileSystem from "effect/FileSystem";
import * as Path from "effect/Path";
import * as Schema from "effect/Schema";
import { McpSchema, Tool, Toolkit } from "effect/ai";
import * as ServerSecretStore from "../../../auth/ServerSecretStore.ts";
import * as ServerConfig from "../../../config.ts";
import * as DocumentText from "../../../provider/DocumentText.ts";
import * as ThreadManagementService from "../../../orchestration-v2/ThreadManagementService.ts";
import * as McpInvocationContext from "../../McpInvocationContext.ts";
import * as PeerTransferReceiver from "../../../peer/PeerTransferReceiver.ts";
import * as PeerTransferSender from "../../../peer/PeerTransferSender.ts";
import * as PeerTransferSource from "../../../peer/PeerTransferSource.ts";
import * as PeerLinks from "../../../peer/PeerLinks.ts";

const shared = {
  failure: OrchestratorMcpFailure,
  failureMode: "return" as const,
  dependencies: [
    McpInvocationContext.McpInvocationContext,
    ThreadManagementService.ThreadManagementService,
    ServerConfig.ServerConfig,
    ServerSecretStore.ServerSecretStore,
    FileSystem.FileSystem,
    Path.Path,
    Crypto.Crypto,
  ],
};
const AttachmentUploadTool = Tool.make("t3_attachment_prepare_upload", {
  ...shared,
  description:
    "Get an upload URL. POST the file's exact bytes to `relativeUrl` on this MCP server's HTTP origin, then send via `t3_thread_send_attachments` with the returned `attachmentId`.",
  parameters: Schema.Struct({ upload: AttachmentCreateUploadUrlInput }),
  success: AttachmentCreateUploadUrlResult,
}).annotate(Tool.Destructive, true);
const AttachmentDiscardTool = Tool.make("t3_attachment_discard", {
  ...shared,
  description: "Discard a pending upload (not a sent attachment).",
  parameters: AttachmentDeleteInput,
  success: Schema.Struct({}),
}).annotate(Tool.Destructive, true);
const AttachmentSendTool = Tool.make("t3_thread_send_attachments", {
  ...shared,
  dependencies: [...shared.dependencies, DocumentText.DocumentText],
  description:
    "Send uploaded attachments as a new message to a thread. No retry key. Target modes cannot exceed yours. Success does not mean the provider read them or finished.",
  parameters: Schema.Struct({
    threadId: Schema.optional(ThreadId),
    message: Schema.optional(Schema.String.check(Schema.isMaxLength(120000))),
    attachments: Schema.Array(McpAttachmentInput).check(
      Schema.isMinLength(1),
      Schema.isMaxLength(8),
    ),
  }),
  success: Schema.Struct({
    threadId: ThreadId,
    messageId: MessageId,
    runId: RunId,
    status: OrchestrationV2RunStatus,
  }),
})
  .annotate(Tool.Destructive, true)
  .annotate(Tool.OpenWorld, true);
const TransferStatus = Schema.Union([
  Schema.Struct({ state: Schema.Literal("receiving"), offset: Schema.Number }),
  Schema.Struct({
    state: Schema.Literal("finished"),
    path: Schema.String,
    sizeBytes: Schema.Number,
    sha256: Schema.String,
  }),
  Schema.Struct({ state: Schema.Literal("aborted") }),
  Schema.Struct({ state: Schema.Literal("interrupted") }),
  Schema.Struct({ state: Schema.Literal("released") }),
  Schema.Struct({ state: Schema.Literal("not_found") }),
]);
const requestId = Schema.String.check(Schema.isPattern(/^\d{13}-[A-Za-z0-9_-]{1,200}$/));
const transferDependencies = [
  ...shared.dependencies,
  PeerTransferSender.PeerTransferSender,
  PeerTransferSource.PeerTransferSource,
  PeerLinks.PeerLinks,
];
const FileTransferTool = Tool.make("t3_file_transfer", {
  ...shared,
  dependencies: transferDependencies,
  description:
    "Transfer the submitted file to the linked environment. Limit 50 MiB. Retry with the same clientRequestId after an unknown outcome.",
  parameters: Schema.Struct({
    environmentId: EnvironmentId,
    clientRequestId: requestId,
  }),
  success: Schema.Struct({ path: Schema.String, sizeBytes: Schema.Number, sha256: Schema.String }),
})
  .annotate(Tool.Destructive, true)
  .annotate(Tool.OpenWorld, true);
const FileTransferPrepareTool = Tool.make("t3_file_transfer_prepare", {
  ...shared,
  dependencies: transferDependencies,
  description:
    "Prepare one private input for a user-authorized file. Set clientRequestId to the current Unix time in milliseconds, a hyphen, and a fresh UUID (for example generated by Node.js). Keep the same ID for retries; it expires after 24 hours on the destination. Run the returned executable with ELECTRON_RUN_AS_NODE=1, optional entrypoint, then `file-transfer-submit`, socketPath, tokenPath and your local file path as separate arguments. Do not print the token contents. Then call t3_file_transfer with the same target and clientRequestId.",
  parameters: Schema.Struct({ environmentId: EnvironmentId, clientRequestId: requestId }),
  success: Schema.Struct({
    socketPath: Schema.String,
    tokenPath: Schema.String,
    executable: Schema.String,
    entrypoint: Schema.optional(Schema.String),
  }),
}).annotate(Tool.Destructive, true);
const FileTransferStatusTool = Tool.make("t3_file_transfer_status", {
  ...shared,
  dependencies: transferDependencies,
  description: "Check the result of your file transfer using the same target and clientRequestId.",
  parameters: Schema.Struct({ environmentId: EnvironmentId, clientRequestId: requestId }),
  success: TransferStatus,
})
  .annotate(Tool.Readonly, true)
  .annotate(Tool.OpenWorld, true);
const FileTransferAbortTool = Tool.make("t3_file_transfer_abort", {
  ...shared,
  dependencies: transferDependencies,
  description: "Abort your unfinished file transfer using the same target and clientRequestId.",
  parameters: Schema.Struct({ environmentId: EnvironmentId, clientRequestId: requestId }),
  success: Schema.Struct({}),
})
  .annotate(Tool.Destructive, true)
  .annotate(Tool.OpenWorld, true);
const FileTransferReleaseTool = Tool.make("t3_file_transfer_release", {
  ...shared,
  dependencies: transferDependencies,
  description:
    "Remove your staged destination file only after verifying that all destination work is finished. The request ID cannot be reused.",
  parameters: Schema.Struct({
    environmentId: EnvironmentId,
    clientRequestId: requestId,
    destinationUseComplete: Schema.Literal(true),
  }),
  success: Schema.Struct({}),
})
  .annotate(Tool.Destructive, true)
  .annotate(Tool.OpenWorld, true);

const peerTransferShared = {
  ...shared,
  dependencies: [...shared.dependencies, PeerTransferReceiver.PeerTransferReceiver],
};
const transferKey = { target: EnvironmentId, requestId };
const PeerTransferBeginTool = Tool.make("t3_peer_transfer_begin", {
  ...peerTransferShared,
  description: "Internal linked-environment transfer operation.",
  parameters: Schema.Struct({ ...transferKey, sizeBytes: Schema.Number, sha256: Schema.String }),
  success: TransferStatus,
})
  .annotate(Tool.Destructive, true)
  .annotate(McpSchema.EnabledWhen, McpInvocationContext.onlyLinkedClient);
const PeerTransferAppendTool = Tool.make("t3_peer_transfer_append", {
  ...peerTransferShared,
  description: "Internal linked-environment transfer operation.",
  parameters: Schema.Struct({
    ...transferKey,
    offset: Schema.Number,
    base64: Schema.String.check(Schema.isMaxLength(349528)),
  }),
  success: TransferStatus,
})
  .annotate(Tool.Destructive, true)
  .annotate(McpSchema.EnabledWhen, McpInvocationContext.onlyLinkedClient);
const PeerTransferFinishTool = Tool.make("t3_peer_transfer_finish", {
  ...peerTransferShared,
  description: "Internal linked-environment transfer operation.",
  parameters: Schema.Struct(transferKey),
  success: TransferStatus,
})
  .annotate(Tool.Destructive, true)
  .annotate(McpSchema.EnabledWhen, McpInvocationContext.onlyLinkedClient);
const PeerTransferStatusTool = Tool.make("t3_peer_transfer_status", {
  ...peerTransferShared,
  description: "Internal linked-environment transfer operation.",
  parameters: Schema.Struct(transferKey),
  success: TransferStatus,
})
  .annotate(Tool.Readonly, true)
  .annotate(McpSchema.EnabledWhen, McpInvocationContext.onlyLinkedClient);
const PeerTransferAbortTool = Tool.make("t3_peer_transfer_abort", {
  ...peerTransferShared,
  description: "Internal linked-environment transfer operation.",
  parameters: Schema.Struct(transferKey),
  success: TransferStatus,
})
  .annotate(Tool.Destructive, true)
  .annotate(McpSchema.EnabledWhen, McpInvocationContext.onlyLinkedClient);
const PeerTransferReleaseTool = Tool.make("t3_peer_transfer_release", {
  ...peerTransferShared,
  description: "Internal linked-environment transfer operation.",
  parameters: Schema.Struct({ ...transferKey, destinationUseComplete: Schema.Literal(true) }),
  success: TransferStatus,
})
  .annotate(Tool.Destructive, true)
  .annotate(McpSchema.EnabledWhen, McpInvocationContext.onlyLinkedClient);
export const AttachmentToolkit = Toolkit.make(
  AttachmentUploadTool,
  AttachmentDiscardTool,
  AttachmentSendTool,
  FileTransferTool,
  FileTransferPrepareTool,
  FileTransferStatusTool,
  FileTransferAbortTool,
  FileTransferReleaseTool,
  PeerTransferBeginTool,
  PeerTransferAppendTool,
  PeerTransferFinishTool,
  PeerTransferStatusTool,
  PeerTransferAbortTool,
  PeerTransferReleaseTool,
);
